import { describe, expect, it } from "vitest";
import { filterFiles, skipReason } from "../../src/diff/filters.js";
import type { DiffLine, FileDiff } from "../../src/diff/types.js";

const file = (path: string, overrides: Partial<FileDiff> = {}): FileDiff => ({
  path,
  status: "modified",
  isBinary: false,
  hunks: [],
  additions: 1,
  deletions: 0,
  ...overrides,
});

/** A file whose single hunk holds the given lines, starting at line 1. */
const withLines = (path: string, status: FileDiff["status"], lines: DiffLine[]): FileDiff =>
  file(path, {
    status,
    hunks: [{ header: "@@", oldStart: 1, oldLines: 0, newStart: 1, newLines: 0, lines }],
  });

const added = (contents: string[]): DiffLine[] =>
  contents.map((content, i) => ({ kind: "add", content, newLine: i + 1 }));

describe("skipReason", () => {
  it.each([
    ["package-lock.json", "lockfile"],
    ["frontend/pnpm-lock.yaml", "lockfile"],
    ["yarn.lock", "lockfile"],
    ["poetry.lock", "lockfile"],
    ["backend/uv.lock", "lockfile"],
    ["Pipfile.lock", "lockfile"],
    ["Cargo.lock", "lockfile"],
    ["go.sum", "lockfile"],
    ["Gemfile.lock", "lockfile"],
    ["composer.lock", "lockfile"],
    ["static/js/app.min.js", "generated"],
    ["static/css/site.min.css", "generated"],
    ["public/app.js.map", "generated"],
    ["dist/index.js", "generated"],
    ["web/build/static/main.js", "generated"],
    ["proto/user_pb2.py", "generated"],
    ["proto/user_pb2_grpc.py", "generated"],
    ["api/user.pb.go", "generated"],
    ["src/api.generated.ts", "generated"],
    ["src/__generated__/graphql.ts", "generated"],
    ["src/__snapshots__/App.test.tsx.snap", "generated"],
    ["vendor/github.com/pkg/errors/errors.go", "vendored"],
    ["node_modules/left-pad/index.js", "vendored"],
    ["lib/third_party/sqlite/sqlite3.c", "vendored"],
    [".venv/lib/python3.12/site-packages/requests/api.py", "vendored"],
    ["venv/bin/activate", "vendored"],
    ["node_modules/.bin/eslint", "vendored"],
    ["dist/.vite/manifest.json", "generated"],
    ["assets/logo.png", "binary"],
    ["assets/photo.JPEG", "binary"],
    ["docs/Report.PDF", "binary"],
    ["release.zip", "binary"],
    ["lib/helper.jar", "binary"],
    ["fonts/Inter.woff2", "binary"],
    ["data/app.sqlite", "binary"],
  ])("skips %s as %s", (path, reason) => {
    expect(skipReason(file(path))).toBe(reason);
  });

  it("skips files the parser marked binary, whatever their extension", () => {
    expect(skipReason(file("data/blob.txt", { isBinary: true }))).toBe("binary");
  });

  it("skips deleted files, since there is nothing left to comment on", () => {
    expect(skipReason(file("app/old_views.py", { status: "deleted" }))).toBe("deleted");
  });

  it.each([
    "app/routes.py",
    "tests/test_app.py",
    "src/vendor.ts",
    "build.py",
    "scripts/dist_utils.py",
    "src/builder/index.ts",
    "src/rebuild/cache.ts",
    "docs/lockfile-format.md",
    "src/package-lock.ts",
    "src/minify.js",
    "README.md",
    ".github/workflows/ci.yml",
  ])("keeps %s", (path) => {
    expect(skipReason(file(path))).toBeUndefined();
  });

  it("detects a generated-file marker at the top of a new file", () => {
    const generated = withLines(
      "src/models.py",
      "added",
      added(["# Code generated by sqlc. DO NOT EDIT.", "class User: ..."]),
    );
    expect(skipReason(generated)).toBe("generated");
  });

  it("detects an @generated marker in the unchanged top lines of a modified file", () => {
    const generated = withLines("src/schema.ts", "modified", [
      { kind: "context", content: "// @generated by graphql-codegen", oldLine: 1, newLine: 1 },
      { kind: "add", content: "export type User = { id: string };", newLine: 2 },
    ]);
    expect(skipReason(generated)).toBe("generated");
  });

  it("reviews a file whose generator header was just removed", () => {
    const nowHandWritten = withLines("src/schema.ts", "modified", [
      { kind: "del", content: "// @generated by graphql-codegen", oldLine: 1 },
      { kind: "add", content: "// Hand-maintained from now on", newLine: 1 },
    ]);
    expect(skipReason(nowHandWritten)).toBeUndefined();
  });

  it("ignores a marker that appears deep inside a hand-written file", () => {
    const lines: DiffLine[] = [
      { kind: "add", content: "# DO NOT EDIT the values below by hand", newLine: 40 },
    ];
    const handWritten = file("app/settings.py", {
      hunks: [{ header: "@@", oldStart: 39, oldLines: 0, newStart: 40, newLines: 1, lines }],
    });
    expect(skipReason(handWritten)).toBeUndefined();
  });
});

describe("filterFiles", () => {
  it("keeps reviewable files in order and lists every skipped file with its reason", () => {
    const result = filterFiles([
      file("package-lock.json"),
      file("app/routes.py"),
      file("assets/logo.png"),
      file("app/models.py"),
      file("app/legacy.py", { status: "deleted" }),
    ]);
    expect(result.kept.map((f) => f.path)).toEqual(["app/routes.py", "app/models.py"]);
    expect(result.skipped).toEqual([
      { path: "package-lock.json", reason: "lockfile" },
      { path: "assets/logo.png", reason: "binary" },
      { path: "app/legacy.py", reason: "deleted" },
    ]);
  });
});
