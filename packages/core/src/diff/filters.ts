import { posix } from "node:path";
import picomatch from "picomatch";
import type { FileDiff, SkipReason, SkippedFile } from "./types.js";

const LOCKFILES = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "bun.lock",
  "bun.lockb",
  "poetry.lock",
  "Pipfile.lock",
  "uv.lock",
  "pdm.lock",
  "Cargo.lock",
  "Gemfile.lock",
  "composer.lock",
  "go.sum",
  "mix.lock",
  "pubspec.lock",
  "Podfile.lock",
  "packages.lock.json",
  "flake.lock",
]);

const isVendored = picomatch(
  [
    "**/vendor/**",
    "**/node_modules/**",
    "**/bower_components/**",
    "**/third_party/**",
    "**/third-party/**",
    "**/.venv/**",
    "**/venv/**",
    "**/site-packages/**",
  ],
  { dot: true },
);

const isGeneratedPath = picomatch(
  [
    "**/*.min.js",
    "**/*.min.css",
    "**/*.map",
    "**/dist/**",
    "**/build/**",
    "**/.next/**",
    "**/coverage/**",
    "**/*_pb2.py",
    "**/*_pb2_grpc.py",
    "**/*.pb.go",
    "**/*.generated.*",
    "**/*.g.dart",
    "**/__generated__/**",
    "**/__snapshots__/**",
    "**/*.snap",
  ],
  { dot: true },
);

const BINARY_EXTENSIONS = new Set(
  (
    "png jpg jpeg gif bmp ico webp tif tiff psd svgz " +
    "pdf doc docx xls xlsx ppt pptx " +
    "zip gz tgz bz2 xz 7z rar tar jar war ear whl egg " +
    "exe dll so dylib bin o a lib class pyc pyo wasm " +
    "woff woff2 ttf otf eot " +
    "mp3 mp4 wav ogg flac mov avi mkv webm " +
    "sqlite sqlite3 db"
  )
    .split(" ")
    .map((ext) => `.${ext}`),
);

/** Markers that code generators put at the top of their output. */
const GENERATED_MARKER = /@generated|DO NOT EDIT|<auto-generated/;
const MARKER_WINDOW = 5;

function hasGeneratedMarker(file: FileDiff): boolean {
  for (const hunk of file.hunks) {
    for (const line of hunk.lines) {
      if (line.kind === "del" || line.newLine > MARKER_WINDOW) continue;
      if (GENERATED_MARKER.test(line.content)) return true;
    }
  }
  return false;
}

/** Why a file should not be reviewed, or undefined if it should be. */
export function skipReason(file: FileDiff): SkipReason | undefined {
  if (file.status === "deleted") return "deleted";
  if (file.isBinary || BINARY_EXTENSIONS.has(posix.extname(file.path).toLowerCase())) {
    return "binary";
  }
  if (isVendored(file.path)) return "vendored";
  if (LOCKFILES.has(posix.basename(file.path))) return "lockfile";
  if (isGeneratedPath(file.path) || hasGeneratedMarker(file)) return "generated";
  return undefined;
}

/** Splits files into those worth reviewing and those skipped (with a reason for each). */
export function filterFiles(files: FileDiff[]): { kept: FileDiff[]; skipped: SkippedFile[] } {
  const kept: FileDiff[] = [];
  const skipped: SkippedFile[] = [];
  for (const file of files) {
    const reason = skipReason(file);
    if (reason) skipped.push({ path: file.path, reason });
    else kept.push(file);
  }
  return { kept, skipped };
}
